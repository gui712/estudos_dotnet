// Create a variable called 'age' and assign it the value 35
int age = 35;
Console.WriteLine($"Age: {age}");

// Create a variable called 'name' and assign it the value "Natalia"
string name = "Natalia";
Console.WriteLine($"Name: {name}");

// Create a variable called height and assign it the value 1.98

double height = 1.98;
Console.WriteLine($"Height: {height}");

//Create a variable called 'Date' and assign it the value 04/09/1999
DateTime date = new DateTime(1999, 9, 4);
Console.WriteLine($"Date: {date}");

// Create a variable called year and assign it the value 12

const int YEAR = 12;
Console.WriteLine($"Year: {YEAR}");

// Create a variable called note and type nullable and assign it the value 7.80
double? note = 7.80;
Console.WriteLine($"Note: {note}");

