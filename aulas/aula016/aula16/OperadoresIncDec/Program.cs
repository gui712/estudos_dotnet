Console.WriteLine("Operators Increment and Decrement");

int a = 5;
int b = 10;

Console.WriteLine("Initial values:");
Console.WriteLine("a = " + a);
Console.WriteLine("b = " + b);

a++; // Increment a
b--; // Decrement b

Console.WriteLine("After incrementing a and decrementing b:");
Console.WriteLine("a = " + a);
Console.WriteLine("b = " + b);
